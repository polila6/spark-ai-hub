const DICTS: Record<Lang, Dict> = { es, en };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey | string) => string };
const I18nCtx = createContext<Ctx>({ lang: "es", setLang: () => {}, t: (k) => String(k) });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("es");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("sah-lang") as Lang | null;
      if (saved === "es" || saved === "en") setLangState(saved);
    } catch {
      /* storage unavailable */
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("sah-lang", l);
    } catch {
      /* ignore */
    }
  }, []);
  const t = useCallback((k: TKey | string) => (DICTS[lang] as Record<string, string>)[k] ?? (es as Record<string, string>)[k] ?? String(k), [lang]);
  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);

/** Inline bilingual text for long, page-specific copy (guides, help): L("texto", "text"). */
export function useL() {
  const { lang } = useContext(I18nCtx);
  return useCallback((es: string, en: string) => (lang === "en" ? en : es), [lang]);
}

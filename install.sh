#!/usr/bin/env bash
# Spark AI Hub — one-command installer for an NVIDIA DGX Spark (or another Linux host with an NVIDIA GPU).
#
#   git clone https://github.com/polila6/spark-ai-hub && cd spark-ai-hub && ./install.sh
#
# Options:
#   --with-studios     also build the ComfyUI (image/video) and ML-worker (audio, science) engines (~30 min)
#   --no-tailscale     do not configure Tailscale Serve (the hub stays on http://127.0.0.1:8080 only)
#   --data-root DIR    where data, models and secrets live (default /srv/spark-ai-hub)
#   --org "NAME"       organisation name shown in terms, e-mails and the assistant (optional)
#   --yes              do not ask questions (use defaults)
# Re-running is safe: existing .env, secrets and data are kept.
set -euo pipefail
cd "$(dirname "$0")"

STUDIOS=0; TS=1; YES=0; DATA_ROOT="${SAH_DATA_ROOT:-/srv/spark-ai-hub}"; ORG="${SAH_ORG_NAME:-}"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --with-studios) STUDIOS=1 ;;
    --no-tailscale) TS=0 ;;
    --data-root) DATA_ROOT="$2"; shift ;;
    --org) ORG="$2"; shift ;;
    --yes|-y) YES=1 ;;
    -h|--help) sed -n 2,13p "$0"; exit 0 ;;
    *) echo "Unknown option $1" >&2; exit 1 ;;
  esac
  shift
done

say()  { printf '\n\033[1;32m==>\033[0m \033[1m%s\033[0m\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf '\033[1;33m !\033[0m  %s\n' "$*"; }
die()  { printf '\033[1;31m x\033[0m  %s\n' "$*" >&2; exit 1; }
ask()  { local q="$1" def="$2" a; if [[ $YES == 1 || ! -t 0 ]]; then echo "$def"; return; fi
         read -r -p "    $q [$def]: " a; echo "${a:-$def}"; }

# ------------------------------------------------------------------ 1. requirements
say "1/6 Checking requirements"
ARCH=$(uname -m)
[[ "$ARCH" == aarch64 ]] && info "Architecture: aarch64 (DGX Spark / GB10) ✓" \
  || warn "Architecture $ARCH: Spark AI Hub is built and tested on the DGX Spark (aarch64). Other NVIDIA hosts may work."
command -v docker >/dev/null || die "Docker is required: https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (docker compose version)."
docker info >/dev/null 2>&1 || die "Your user cannot use Docker. Run: sudo usermod -aG docker $USER  (then log out and in)."
docker info --format '{{json .Runtimes}}' | grep -q nvidia \
  || die "NVIDIA Container Toolkit not found: https://docs.nvidia.com/datacenter/cloud-native/container-toolkit/"
if command -v nvidia-smi >/dev/null; then info "GPU: $(nvidia-smi --query-gpu=name --format=csv,noheader | head -1) ✓"; fi
MEM_GB=$(awk '/MemTotal/ {printf "%d", $2/1024/1024}' /proc/meminfo)
(( MEM_GB >= 60 )) && info "Memory: ${MEM_GB} GB ✓" || warn "Memory: ${MEM_GB} GB. 64 GB or more is recommended (128 GB on the DGX Spark)."
PARENT="$DATA_ROOT"; while [[ ! -d "$PARENT" ]]; do PARENT=$(dirname "$PARENT"); done
FREE_GB=$(df -BG --output=avail "$PARENT" | tail -1 | tr -dc 0-9)
(( FREE_GB >= 150 )) && info "Free disk for $DATA_ROOT: ${FREE_GB} GB ✓" \
  || warn "Only ${FREE_GB} GB free for $DATA_ROOT. Models need space: 150 GB or more is recommended."
[[ $(id -u) == 1000 ]] || warn "Containers run as uid 1000 and your uid is $(id -u): data in $DATA_ROOT will be owned by uid 1000."
command -v python3 >/dev/null || die "python3 is required (used to generate secrets)."

# ------------------------------------------------------------------ 2. configuration (.env)
say "2/6 Configuration"
if [[ -f .env ]]; then
  info ".env already exists: keeping it."
else
  URL="http://127.0.0.1:8080"
  if [[ $TS == 1 ]] && command -v tailscale >/dev/null && tailscale status >/dev/null 2>&1; then
    DNS=$(tailscale status --json | python3 -c 'import json,sys;print(json.load(sys.stdin)["Self"]["DNSName"].rstrip("."))' 2>/dev/null || true)
    [[ -n "$DNS" ]] && URL="https://$DNS"
  elif [[ $TS == 1 ]]; then
    warn "Tailscale is not installed or not logged in: the hub will only be reachable from this machine."
    info "Install it (https://tailscale.com/download), run 'sudo tailscale up' and re-run ./install.sh to add HTTPS access."
    TS=0
  fi
  URL=$(ask "Address people will use to open the hub" "$URL")
  ORG=$(ask "Organisation name (optional, e.g. 'Robotics Lab · Example University')" "$ORG")
  GID=$(stat -c %g /var/run/docker.sock)
  (umask 077; cat > .env <<EOF
# Generated by install.sh on $(date -I). Never commit this file.
SAH_DATA_ROOT=$DATA_ROOT
SAH_PROXY_PORT=8080
SAH_PUBLIC_BASE_URL=$URL
SAH_ORG_NAME=$ORG
SAH_COOKIE_SECURE=$([[ $URL == https://* ]] && echo true || echo false)
SAH_DOCKER_GID=$GID
SAH_IMPORT_HF_CACHE=$HOME/.cache/huggingface
EOF
)
  info "Wrote .env (address $URL)"
fi
set -a; source .env; set +a
DATA_ROOT="${SAH_DATA_ROOT:-$DATA_ROOT}"
mkdir -p "${SAH_IMPORT_HF_CACHE:-$HOME/.cache/huggingface}"

# ------------------------------------------------------------------ 3. host preparation (sudo, once)
say "3/6 Preparing $DATA_ROOT (asks for your sudo password once)"
SKIP_TS=$([[ $TS == 1 && "${SAH_PUBLIC_BASE_URL:-}" == https://* ]] && echo 0 || echo 1)
sudo SAH_DATA_ROOT="$DATA_ROOT" SAH_PROXY_PORT="${SAH_PROXY_PORT:-8080}" SAH_SKIP_TAILSCALE="$SKIP_TS" \
  SAH_OWNER="$(id -un)" bash scripts/host-setup.sh
if [[ $(id -u) != 1000 ]]; then sudo chown -R 1000:1000 "$DATA_ROOT" && sudo chown 999:999 "$DATA_ROOT/database"; fi

# ------------------------------------------------------------------ 4. secrets
say "4/6 Generating secrets (kept in $DATA_ROOT/config/secrets, never in git)"
SAH_DATA_ROOT="$DATA_ROOT" bash scripts/init-secrets.sh | grep -v "initial password" || true

# ------------------------------------------------------------------ 5. images
say "5/6 Pulling and building images (first time: 20–40 min, ~40 GB download)"
docker pull "${SAH_VLLM_IMAGE:-nvcr.io/nvidia/vllm:26.09-py3}"
docker compose build
docker compose -f compose.yaml -f compose.optional.yaml --profile sandbox build sandbox   # code execution for the chat
if [[ $STUDIOS == 1 ]]; then
  docker compose -f compose.yaml -f compose.optional.yaml --profile engines build comfyui mlworker
else
  info "Image/video/audio studios skipped (add them later with: ./install.sh --with-studios)."
fi

# ------------------------------------------------------------------ 6. start
say "6/6 Starting Spark AI Hub"
docker compose up -d
printf '    Waiting for the hub'
for _ in $(seq 1 90); do
  if curl -fs "http://127.0.0.1:${SAH_PROXY_PORT:-8080}/api/v1/system/health" >/dev/null 2>&1; then ok=1; break; fi
  printf '.'; sleep 4
done
echo
[[ "${ok:-0}" == 1 ]] || die "The hub did not become healthy. Check: docker compose ps; docker compose logs backend"

PW_FILE="$DATA_ROOT/config/secrets/admin_password"
cat <<EOF

  ✅ Spark AI Hub is running.

  Open:      ${SAH_PUBLIC_BASE_URL}
  User:      admin
  Password:  cat $PW_FILE      (change it after the first login)

  Next steps (also shown in the app, "Help" page):
   1. Discover models → search "Qwen3.5-35B-A3B-FP8" → Install, then pin it as the general model
      (Library → model → "Pin"). It answers chat, agents, OpenCode and Claude Code.
   2. Settings → Users: invite people by e-mail, or allow sign-up requests.
   3. Connect tools: OpenCode, Claude Code, Cline, Continue, Python… with a personal API key.

  Operations: scripts/sah.sh status | logs backend | backup | update
EOF
